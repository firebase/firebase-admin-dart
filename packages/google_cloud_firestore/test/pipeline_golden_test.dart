      final missing = [
        for (final id in fixtures.keys)
          if (!registry.cases.containsKey(id) && !_dartApiGaps.containsKey(id))
            id,
      ];
      expect(
        missing,
        isEmpty,
        reason:
            'Add a Dart case to _registerCases for each of these fixture '
            'ids, or list it in _dartApiGaps.',
      );
    });

    test('every Dart case has a fixture', () {
      final orphans = [
        for (final id in registry.cases.keys)
          if (!fixtures.containsKey(id)) id,
      ];
      expect(
        orphans,
        isEmpty,
        reason:
            'Add these cases to tool/pipeline_golden/cases.js and regenerate '
            'the fixtures (see tool/pipeline_golden/README.md).',
      );
    });

    test('documented API gaps have a fixture and no Dart case', () {
      for (final id in _dartApiGaps.keys) {
        expect(fixtures, contains(id), reason: '_dartApiGaps lists $id');
        expect(
          registry.cases,
          isNot(contains(id)),
          reason: '$id has a Dart case: remove it from _dartApiGaps.',
        );
      }
    });

    test('divergences and pending fixes have a fixture and a Dart case', () {
      for (final id in [..._knownDivergences.keys, ..._pendingFixes.keys]) {
        expect(fixtures, contains(id));
        expect(registry.cases, contains(id));
      }
      expect(
        _knownDivergences.keys.toSet().intersection(_pendingFixes.keys.toSet()),
        isEmpty,
      );
    });
  });

  group('matches the Node SDK request', () {
    late _MockFirestoreHttpClient client;
    late Firestore db;
    firestore_v1.ExecutePipelineRequest? captured;

    setUp(() {
      client = _MockFirestoreHttpClient();
      when(() => client.cachedProjectId).thenReturn(_projectId);
      when(
        () => client.v1<Stream<firestore_v1.ExecutePipelineResponse>>(any()),
      ).thenAnswer((invocation) async {
        final callback =
            invocation.positionalArguments.single
                as Future<Stream<firestore_v1.ExecutePipelineResponse>>
                Function(firestore_v1.Firestore api, String projectId);
        final api = FakeFirestore(
          executePipeline: (request) {
            captured = request;
            return const Stream<firestore_v1.ExecutePipelineResponse>.empty();
          },
        );
        return callback(api, _projectId);
      });
      db = Firestore.internal(
        settings: const Settings(
          projectId: _projectId,
          databaseId: _databaseId,
        ),
        client: client,
      );
    });

    Future<Object?> capture(_Run run) async {
      captured = null;
      await run(db);
      final request = captured;
      if (request == null) fail('The case sent no request.');
      return _canonicalize(jsonDecode(jsonEncode(request.toJson())));
    }

    for (final id in fixtures.keys.toList()..sort()) {
      final runs = registry.cases[id];
      if (runs == null) continue;
      final expected = fixtures[id];

      test(id, () async {
        for (final (index, run) in runs.indexed) {
          final actual = await capture(run);
          final form = runs.length == 1 ? '' : ' (Dart form #${index + 1})';
          final differences = <String>[];
          _diff(expected, actual, r'$', differences);

          final divergence = _knownDivergences[id];
          final pending = _pendingFixes[id];
          if (divergence != null) {
            expect(
              differences,
              isNotEmpty,
              reason:
                  '$id$form now matches Node: remove it from '
                  '_knownDivergences.',
            );
            expect(
              divergence.check(actual),
              isTrue,
              reason:
                  '$id$form no longer has the intended shape: '
                  '${divergence.reason}\n'
                  'Dart sent:\n${_pretty(actual)}',
            );
          } else if (pending != null) {
            expect(
              differences,
              isNotEmpty,
              reason:
                  '$id$form now matches Node: remove it from '
                  '_pendingFixes.',
            );
          } else if (differences.isNotEmpty) {
            fail(
              '$id$form differs from the Node SDK request:\n'
              '  ${differences.join('\n  ')}\n\n'
              'Dart sent:\n${_pretty(actual)}\n\n'
              'Node sent:\n${_pretty(expected)}',
            );
          }
        }
      });
    }
  });
}

