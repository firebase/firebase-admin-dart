/// Loads every case of every fixture file, keyed by id.
Map<String, Object?> _loadFixtures() {
  final files =
      Directory(_fixtureDir)
          .listSync()
          .whereType<File>()
          .where((file) => file.path.endsWith('.json'))
          .toList()
        ..sort((a, b) => a.path.compareTo(b.path));
  if (files.isEmpty) {
    throw StateError('No fixtures in $_fixtureDir; run from the package root.');
  }

  final result = <String, Object?>{};
  for (final file in files) {
    final json = jsonDecode(file.readAsStringSync()) as Map<String, Object?>;
    final cases = json['cases']! as Map<String, Object?>;
    for (final MapEntry(:key, :value) in cases.entries) {
      if (result.containsKey(key)) {
        throw StateError('Duplicate fixture id $key in ${file.path}.');
      }
      result[key] = _canonicalize(value);
    }
  }
  return result;
}

/// Repeated and map fields that proto3 JSON omits when empty.
///
/// The same normalization `tool/pipeline_golden/generate.js` applies.
const _omitWhenEmpty = {'args', 'options', 'fields', 'values'};

/// Sorts keys (`name` first, as in the fixtures) and drops [_omitWhenEmpty]
/// fields that are empty.
Object? _canonicalize(Object? value) {
  return switch (value) {
    List() => [for (final item in value) _canonicalize(item)],
    Map() => {
      for (final key in value.keys.cast<String>().toList()..sort(_compareKeys))
        if (_canonicalize(value[key]) case final child
            when !(_omitWhenEmpty.contains(key) && _isEmpty(child)))
          key: child,
    },
    _ => value,
  };
}

int _compareKeys(String a, String b) {
  if (a == b) return 0;
  if (a == 'name') return -1;
  if (b == 'name') return 1;
  return a.compareTo(b);
}

bool _isEmpty(Object? value) {
  return switch (value) {
    List() => value.isEmpty,
    Map() => value.isEmpty,
    _ => false,
  };
}

/// Lists the paths at which [expected] and [actual] differ.
///
/// Numbers compare by value, so `1` and `1.0` (a `doubleValue` encoded by
/// JavaScript and by Dart) are equal.
void _diff(Object? expected, Object? actual, String path, List<String> out) {
  if (expected is Map && actual is Map) {
    for (final key in {...expected.keys, ...actual.keys}) {
      final child = '$path.$key';
      if (!expected.containsKey(key)) {
        out.add('$child: missing in Node, Dart has ${_short(actual[key])}');
      } else if (!actual.containsKey(key)) {
        out.add('$child: Node has ${_short(expected[key])}, missing in Dart');
      } else {
        _diff(expected[key], actual[key], child, out);
      }
    }
  } else if (expected is List && actual is List) {
    if (expected.length != actual.length) {
      out.add(
        '$path: Node has ${expected.length} items, Dart has '
        '${actual.length}: Node ${_short(expected)}, Dart ${_short(actual)}',
      );
      return;
    }
    for (var i = 0; i < expected.length; i++) {
      _diff(expected[i], actual[i], '$path[$i]', out);
    }
  } else if (expected != actual) {
    out.add('$path: Node ${_short(expected)}, Dart ${_short(actual)}');
  }
}

String _short(Object? value) {
  final json = jsonEncode(value);
  return json.length <= 200 ? json : '${json.substring(0, 200)}...';
}

String _pretty(Object? value) =>
    const JsonEncoder.withIndent('  ').convert(value);

/// A deliberate difference from the Node SDK.
final class _Divergence {
  const _Divergence(this.reason, this.check);

  /// Why this SDK sends something else.
  final String reason;

  /// Whether the canonical Dart request has the intended shape.
  final bool Function(Object? request) check;
}

/// Whether the `where` stage's function receives its search space as an
/// `array(...)` function.
bool _searchSpaceIsArrayFunction(Object? request) {
  final stages = _path(request, ['structuredPipeline', 'pipeline', 'stages']);
  if (stages is! List || stages.length != 2) return false;
  final searchSpace = _path(stages[1], ['args', 0, 'functionValue', 'args', 1]);
  return _path(searchSpace, ['functionValue', 'name']) == 'array';
}

Object? _path(Object? value, List<Object> path) {
  var current = value;
  for (final segment in path) {
    current = switch ((current, segment)) {
      (final Map<Object?, Object?> map, final String key) => map[key],
      (final List<Object?> list, final int index) when index < list.length =>
        list[index],
      _ => null,
    };
  }
  return current;
}

