/// Compares the Pipeline requests this SDK sends with the ones the Node.js
/// SDK sends for the same Pipelines.
///
/// The expected requests in `test/fixtures/pipeline_golden/*.json` are
/// generated by the Node.js SDK (see `tool/pipeline_golden/README.md`), never
/// by this package. Every fixture id has a Dart case below that builds the
/// equivalent Pipeline; the request it sends must equal the fixture.
