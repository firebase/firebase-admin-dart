/// Executes a Pipeline against [db]; the request it sends is captured.
typedef _Run = Future<Object?> Function(Firestore db);

typedef _Build = Pipeline Function(Firestore db);
typedef _Expr = PipelineExpression Function();
typedef _DbExpr = PipelineExpression Function(Firestore db);
typedef _Static1 = PipelineExpression Function(Object? target);
typedef _Method0 = PipelineExpression Function(PipelineExpression target);
typedef _Static2 = PipelineExpression Function(Object? target, Object? operand);
typedef _Method1 =
    PipelineExpression Function(PipelineExpression target, Object? operand);

/// The Dart cases, keyed by fixture id.
///
/// A case may have several Dart forms (for example a top-level helper and
/// the matching [PipelineFunctions] member); each one must match.
final class _Registry {
  final cases = <String, List<_Run>>{};

  void run(String id, List<_Run> runs) {
    if (cases.containsKey(id)) throw StateError('Duplicate case id $id.');
    cases[id] = runs;
  }

  /// A Pipeline executed without options.
  void pipeline(
    String id,
    _Build build, [
    List<_Build> alternatives = const [],
  ]) {
    run(id, [
      for (final b in [build, ...alternatives]) (db) => b(db).execute(),
    ]);
  }

  /// A function wrapped as in `cases.js`: boolean expressions in `where`,
  /// everything else in `select(<expr>.as('result'))`.
  void expr(String id, _Expr build, [List<_Expr> alternatives = const []]) {
    pipeline(id, (db) => _wrap(db, build()), [
      for (final b in alternatives) (db) => _wrap(db, b()),
    ]);
  }

  /// A function that needs the Firestore instance, such as for a reference.
  void dbExpr(String id, _DbExpr build) {
    pipeline(id, (db) => _wrap(db, build(db)));
  }

  /// An aggregate function, in `aggregate(<expr>.as('result'))`.
  void aggregate(
    String id,
    _Expr build, [
    List<_Expr> alternatives = const [],
  ]) {
    pipeline(id, (db) => _books(db).aggregate([build().as('result')]), [
      for (final b in alternatives)
        (db) => _books(db).aggregate([b().as('result')]),
    ]);
  }

  /// Mirrors `unary` in `cases.js`.
  void unary(
    String name,
    String target,
    _Static1 static,
    _Method0 method, {
    String area = 'functions',
  }) {
    final register = area == 'aggregates' ? aggregate : expr;
    register('$area/$name/static-field-name', () => static(target));
    register('$area/$name/static-expression', () => static(field(target)));
    register('$area/$name/method', () => method(field(target)));
  }

  /// Mirrors `binary` in `cases.js`.
  void binary(
    String name,
    String target,
    Object? literal,
    _Expr operand,
    _Static2 static,
    _Method1 method, {
    List<_Static2> staticAlternatives = const [],
    List<_Method1> methodAlternatives = const [],
  }) {
    final statics = [static, ...staticAlternatives];
    final methods = [method, ...methodAlternatives];
    void staticCase(
      String variant,
      Object? Function() target,
      Object? Function() op,
    ) {
      expr('functions/$name/static-$variant', () => static(target(), op()), [
        for (final s in statics.skip(1)) () => s(target(), op()),
      ]);
    }

    staticCase('field-name-literal', () => target, () => literal);
    staticCase('field-name-expression', () => target, operand);
    staticCase('expression-literal', () => field(target), () => literal);
    staticCase('expression-expression', () => field(target), operand);
    expr(
      'functions/$name/method-literal',
      () => method(field(target), literal),
      [for (final m in methods.skip(1)) () => m(field(target), literal)],
    );
    expr(
      'functions/$name/method-expression',
      () => method(field(target), operand()),
    );
  }
}

Pipeline _books(Firestore db) => db.pipeline().collection('books');

Pipeline _wrap(Firestore db, PipelineExpression expression) {
  return switch (expression) {
    PipelineBooleanExpression() => _books(db).where(expression),
    _ => _books(db).select([expression.as('result')]),
  };
}

